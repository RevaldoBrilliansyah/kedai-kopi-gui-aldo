    private String formatRupiah(int nominal){
        return "Rp." + String.format(java.util.Locale.forLanguageTag("id-ID"), "%,d", nominal);
    }
    
    private void hitungTotal(){
        int total = 25000;
        
        if(cbxGulaAren.isSelected()){
            total += 3000;
        }
        if(cbxSusuOat.isSelected()){
            total += 5000;
        }
        if(cbxExtraShot.isSelected()){
            total += 4000;
        }
        
        lblTotalHarga.setText(formatRupiah(total));
    }
